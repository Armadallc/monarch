const PortalKanbanBoard = ({
    referrals,
    selectedReferralId,
    selectedIds,
    onToggleSelect,
    onOpenReferral,
    programNamesById,
    staffAssigneeByUserId,
}: {
    referrals: PortalReferral[]
    selectedReferralId?: string | null
    selectedIds?: Set<string>
    onToggleSelect?: (id: string) => void
    onOpenReferral: (referral: PortalReferral) => void
    programNamesById: Record<string, string>
    staffAssigneeByUserId: Record<string, PortalAssigneeProfile | undefined>
}) => {
    const [collapsedColumns, setCollapsedColumns] = useState<Set<ReferralStatus>>(() => new Set())

    const byColumn = useMemo(() => {
        const map = new Map<ReferralStatus, PortalReferral[]>()
        for (const col of PORTAL_KANBAN_COLUMNS) map.set(col.status, [])
        for (const r of referrals) {
            const list = map.get(r.status as ReferralStatus)
            if (list) list.push(r)
        }
        return map
    }, [referrals])

    const toggleColumnCollapse = (status: ReferralStatus) => {
        setCollapsedColumns((prev) => {
            const next = new Set(prev)
            if (next.has(status)) next.delete(status)
            else next.add(status)
            return next
        })
    }

    return (
        <div
            style={{
                display: "flex",
                flexDirection: "column",
                flex: 1,
                minHeight: 0,
                fontFamily: FONT,
            }}
        >
            <div
                style={{
                    display: "flex",
                    overflowX: "auto",
                    overflowY: "hidden",
                    flex: 1,
                    minHeight: 0,
                    width: "100%",
                    height: "100%",
                    paddingBottom: 8,
                    alignItems: "stretch",
                    alignSelf: "stretch",
                    border: `1px solid ${COLORS.ashSubtle}`,
                    borderRadius: RADIUS.small,
                    boxSizing: "border-box",
                }}
            >
                <div style={{ display: "flex", flex: 1, minWidth: 0, gap: 12, height: "100%", alignItems: "stretch", padding: "4px 4px 4px 8px" }}>
                    {PORTAL_KANBAN_COLUMNS.map((col) => {
                        const columnReferrals = byColumn.get(col.status) ?? []
                        const collapsed = collapsedColumns.has(col.status)
                        const columnSize = collapsed
                            ? {
                                  flex: `0 0 ${PORTAL_KANBAN_COLUMN_COLLAPSED_WIDTH}px`,
                                  minWidth: PORTAL_KANBAN_COLUMN_COLLAPSED_WIDTH,
                                  maxWidth: PORTAL_KANBAN_COLUMN_COLLAPSED_WIDTH,
                              }
                            : {
                                  flex: "1 1 0%",
                                  minWidth: PORTAL_KANBAN_COLUMN_FILL_MIN,
                              }

                        return (
                            <div
                                key={col.status}
                                style={{
                                    ...columnSize,
                                    height: "100%",
                                    minHeight: 0,
                                    display: "flex",
                                    flexDirection: "column",
                                    transition: TRANSITION,
                                }}
                            >
                                <div
                                    style={{
                                        flexShrink: 0,
                                        padding: collapsed ? "12px 0" : "12px 14px",
                                        ...(collapsed ? { marginBottom: 0 } : { margin: "5px 0 10px 12px" }),
                                        borderRadius: collapsed ? RADIUS.small : 0,
                                        background: COLORS.sidebar,
                                        color: COLORS.ash,
                                        fontFamily: FONT,
                                        height: collapsed ? "100%" : undefined,
                                        display: "flex",
                                        flexDirection: "column",
                                        border: "none",
                                        borderBottom: collapsed ? undefined : `2px solid ${COLORS.primary}`,
                                    }}
                                >
                                    {collapsed ? (
                                        <div style={{ display: "flex", flexDirection: "column", alignItems: "center", justifyContent: "flex-start", gap: 10, height: "100%", minWidth: PORTAL_KANBAN_COLUMN_COLLAPSED_WIDTH }}>
                                            <span style={{ fontSize: 11, fontWeight: 600, background: COLORS.sidebarAccent, padding: "2px 8px", borderRadius: RADIUS.pill, lineHeight: 1.3, color: COLORS.onChrome }}>
                                                {columnReferrals.length}
                                            </span>
                                            <PortalKanbanColumnCollapseButton collapsed={collapsed} title={col.title} onClick={() => toggleColumnCollapse(col.status)} />
                                            <span
                                                title={col.title}
                                                style={{
                                                    flex: 1,
                                                    fontSize: 11,
                                                    fontWeight: 600,
                                                    fontFamily: FONT_HEADING,
                                                    letterSpacing: "0.06em",
                                                    textTransform: "uppercase",
                                                    writingMode: "vertical-rl",
                                                    textOrientation: "mixed",
                                                    transform: "rotate(180deg)",
                                                    lineHeight: 1.2,
                                                    opacity: 0.75,
                                                    overflow: "hidden",
                                                    textOverflow: "ellipsis",
                                                    whiteSpace: "nowrap",
                                                    maxHeight: "100%",
                                                    textAlign: "right",
                                                    paddingBottom: 20,
                                                }}
                                            >
                                                {col.title}
                                            </span>
                                        </div>
                                    ) : (
                                        <div style={{ display: "flex", justifyContent: "space-between", alignItems: "center", gap: 8 }}>
                                            <span
                                                style={{
                                                    fontSize: 13,
                                                    fontWeight: 600,
                                                    fontFamily: FONT_HEADING,
                                                    color: COLORS.ash,
                                                    letterSpacing: "0.04em",
                                                    textTransform: "uppercase",
                                                    opacity: 0.75,
                                                    minWidth: 0,
                                                    overflow: "hidden",
                                                    textOverflow: "ellipsis",
                                                    whiteSpace: "nowrap",
                                                    flex: 1,
                                                }}
                                            >
                                                {col.title}
                                            </span>
                                            <div style={{ display: "flex", alignItems: "center", gap: 6, flexShrink: 0 }}>
                                                <span style={{ fontSize: 12, fontWeight: 600, background: COLORS.sidebarAccent, padding: "2px 10px", borderRadius: RADIUS.pill, color: COLORS.onChrome }}>
                                                    {columnReferrals.length}
                                                </span>
                                                <PortalKanbanColumnCollapseButton collapsed={collapsed} title={col.title} onClick={() => toggleColumnCollapse(col.status)} />
                                            </div>
                                        </div>
                                    )}
                                </div>
                                {!collapsed && (
                                    <div
                                        style={{
                                            flex: 1,
                                            minHeight: 0,
                                            overflowY: "auto",
                                            overflowX: "hidden",
                                            WebkitOverflowScrolling: "touch",
                                            padding: 8,
                                            borderRadius: RADIUS.section,
                                            background: COLORS.coconut25,
                                            border: `1px dashed ${COLORS.ashSubtle}`,
                                            display: "flex",
                                            flexDirection: "column",
                                            gap: 8,
                                        }}
                                    >
                                        {columnReferrals.length === 0 ? (
                                            <p style={{ margin: 0, padding: 12, fontSize: 12, color: COLORS.ashMuted, fontFamily: FONT, textAlign: "center" }}>No referrals</p>
                                        ) : (
                                            columnReferrals.map((referral) => (
                                                <PortalKanbanCard
                                                    key={referral.id}
                                                    referral={referral}
                                                    selected={selectedReferralId === referral.id}
                                                    checked={selectedIds?.has(referral.id)}
                                                    onToggleSelect={onToggleSelect}
                                                    onOpen={onOpenReferral}
                                                    programLabel={(() => {
                                                        const label = resolvePortalProgramRowLabel(referral, programNamesById)
                                                        return label === "\u2014" ? "" : label
                                                    })()}
                                                    assigneeName={portalAssigneeDisplayName(referral, staffAssigneeByUserId)}
                                                />
                                            ))
                                        )}
                                    </div>
                                )}
                            </div>
                        )
                    })}
                </div>
            </div>
        </div>
    )
}

