/**
 * Escape `\`, `%`, `_` for use in PostgREST `ilike` filter values (exact match, no wildcards).
 */
function escapeIlikeLiteral(s: string): string {
    return s.replace(/\\/g, "\\\\").replace(/%/g, "\\%").replace(/_/g, "\\_")
}

/**
 * PostgREST `.or()` filter for rows this source should see. Email side uses ilike with
 * reserved chars escaped and value double-quoted so addresses with `.` parse correctly.
 */
function portalReferralsOwnershipOr(userId: string, userEmail: string): string {
    const trimmed = userEmail.trim()
    const escaped = escapeIlikeLiteral(trimmed).replace(/"/g, '""')
    return `submitted_by_user_id.eq.${userId},referral_source_email.ilike."${escaped}"`
}

