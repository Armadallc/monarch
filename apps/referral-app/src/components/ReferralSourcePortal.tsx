type PortalSortState = {
    column: string
    direction: "asc" | "desc"
}

function filterAndSortPortalReferrals(
    source: PortalReferral[],
    opts: {
        summaryFilter?: PortalSummaryFilter
        searchQuery: string
        filters: PortalListFilters
        sort: PortalSortState
        programNamesById: Record<string, string>
        staffAssigneeByUserId: Record<string, PortalAssigneeProfile | undefined>
    }
): PortalReferral[] {
    let f = opts.summaryFilter ? applyPortalSummaryFilter(source, opts.summaryFilter) : source
    const qRaw = opts.searchQuery.trim().toLowerCase()
    if (qRaw) {
        f = f.filter(
            (s) =>
                (s.client_first_name || "").toLowerCase().includes(qRaw) ||
                (s.client_last_name || "").toLowerCase().includes(qRaw) ||
                (s.referral_source_name || "").toLowerCase().includes(qRaw) ||
                (s.court_jurisdiction || "").toLowerCase().includes(qRaw) ||
                (s.case_number || "").toLowerCase().includes(qRaw) ||
                (s.referral_code || "").toLowerCase().includes(qRaw) ||
                (s.admin_ref_id || "").toLowerCase().includes(qRaw) ||
                (s.attorney_name || "").toLowerCase().includes(qRaw) ||
                (s.competency_status || "").toLowerCase().includes(qRaw) ||
                (s.facility_name || "").toLowerCase().includes(qRaw) ||
                resolvePortalProgramRowLabel(s, opts.programNamesById).toLowerCase().includes(qRaw) ||
                (s.assigned_to_user_id
                    ? [opts.staffAssigneeByUserId[s.assigned_to_user_id]?.display_name, opts.staffAssigneeByUserId[s.assigned_to_user_id]?.title]
                          .filter(Boolean)
                          .join(" ")
                          .toLowerCase()
                          .includes(qRaw)
                    : false)
        )
    }
    if (opts.filters.sourceType !== "all") {
        f = f.filter((s) => s.referral_source_type === opts.filters.sourceType)
    }
    if (opts.filters.status !== "all") {
        f = f.filter((s) => s.status === opts.filters.status)
    }
    if (opts.filters.urgent !== "all") {
        f = f.filter((s) => !!s.urgent_placement === (opts.filters.urgent === "true"))
    }
    if (opts.filters.assigned === "assigned") f = f.filter((s) => !!s.assigned_to_user_id)
    if (opts.filters.assigned === "unassigned") f = f.filter((s) => !s.assigned_to_user_id)
    if (opts.filters.program !== "all") {
        f = f.filter((s) => resolvePortalProgramRowLabel(s, opts.programNamesById) === opts.filters.program)
    }

    const col = opts.sort.column
    const dir = opts.sort.direction
    return [...f].sort((a, b) => {
        let aV: unknown
        let bV: unknown
        if (col === "program_display") {
            aV = resolvePortalProgramRowLabel(a, opts.programNamesById)
            bV = resolvePortalProgramRowLabel(b, opts.programNamesById)
        } else if (col === "assignee_display") {
            const pa = a.assigned_to_user_id ? opts.staffAssigneeByUserId[a.assigned_to_user_id] : undefined
            const pb = b.assigned_to_user_id ? opts.staffAssigneeByUserId[b.assigned_to_user_id] : undefined
            aV = [pa?.display_name?.trim(), pa?.title?.trim()].filter(Boolean).join(" ") || ""
            bV = [pb?.display_name?.trim(), pb?.title?.trim()].filter(Boolean).join(" ") || ""
        } else {
            aV = (a as Record<string, unknown>)[col]
            bV = (b as Record<string, unknown>)[col]
        }
        if (typeof aV === "boolean") {
            aV = aV ? 1 : 0
            bV = bV ? 1 : 0
        }
        if (col === "last_activity_at") {
            aV = new Date((a.last_activity_at || a.created_at) as string).getTime()
            bV = new Date((b.last_activity_at || b.created_at) as string).getTime()
        } else if (col === "created_at" || col === "updated_at") {
            aV = new Date((aV as string) || 0).getTime()
            bV = new Date((bV as string) || 0).getTime()
        }
        const aS = String(aV ?? "")
        const bS = String(bV ?? "")
        if (dir === "asc") {
            return typeof aV === "number" && typeof bV === "number" ? aV - bV : aS.localeCompare(bS)
        }
        return typeof aV === "number" && typeof bV === "number" ? bV - aV : bS.localeCompare(aS)
    })
}

