const MONARCH_THEME_STORAGE_KEY = "monarch-dashboard-theme"

type MonarchThemeMode = "light" | "dark" | "system"

function getStoredMonarchThemeMode(): MonarchThemeMode {
    try {
        const stored = localStorage.getItem(MONARCH_THEME_STORAGE_KEY)
        if (stored === "light" || stored === "dark" || stored === "system") return stored
    } catch {
        /* ignore */
    }
    return "system"
}

function resolveMonarchThemeMode(mode: MonarchThemeMode): "light" | "dark" {
    if (mode === "light" || mode === "dark") return mode
    return typeof window !== "undefined" && window.matchMedia("(prefers-color-scheme: dark)").matches ? "dark" : "light"
}

function applyMonarchThemeMode(mode: MonarchThemeMode): "light" | "dark" {
    const resolved = resolveMonarchThemeMode(mode)
    if (typeof document !== "undefined") {
        document.documentElement.classList.toggle("dark", resolved === "dark")
        document.documentElement.dataset.theme = resolved
    }
    try {
        localStorage.setItem(MONARCH_THEME_STORAGE_KEY, mode)
    } catch {
        /* ignore */
    }
    if (typeof window !== "undefined") {
        window.dispatchEvent(new CustomEvent("monarch-theme-change"))
    }
    return resolved
}

function useMonarchThemeBootstrap() {
    useEffect(() => {
        if (typeof document === "undefined") return
        const id = "monarch-dashboard-theme-vars"
        if (!document.getElementById(id)) {
            const el = document.createElement("style")
            el.id = id
            el.textContent = MONARCH_THEME_INJECT_CSS
            document.head.appendChild(el)
        }
        applyMonarchThemeMode(getStoredMonarchThemeMode())
        const mq = window.matchMedia("(prefers-color-scheme: dark)")
        const onSystemChange = () => {
            if (getStoredMonarchThemeMode() === "system") applyMonarchThemeMode("system")
        }
        mq.addEventListener("change", onSystemChange)
        return () => mq.removeEventListener("change", onSystemChange)
    }, [])
}

