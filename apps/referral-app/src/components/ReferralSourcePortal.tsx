function portalAssigneeDisplayName(
    referral: PortalReferral,
    staffAssigneeByUserId: Record<string, PortalAssigneeProfile | undefined>
): string | null {
    const uid = referral.assigned_to_user_id
    if (!uid) return null
    const profile = staffAssigneeByUserId[uid]
    return profile?.display_name?.trim() || null
}

