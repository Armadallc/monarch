function PortalKanbanCardIndicators({ referral }: { referral: PortalReferral }) {
    const showAttachments = portalReferralHasAttachments(referral)
    const showUnreadMessages = !!referral.has_unread_messages
    const expeditedMode = expeditedPlacementDisplay(referral.urgent_placement, referral.urgency_level)
    const urgencyIcon =
        expeditedMode === "lightning_circled" ? (
            <PortalKanbanExpeditedIcon mode="lightning_circled" />
        ) : expeditedMode === "lightning" ? (
            <PortalKanbanExpeditedIcon mode="lightning" />
        ) : null
    const statusIcon =
        referral.status === "accepted" ? (
            <PortalKanbanAcceptedIcon />
        ) : referral.status === "declined" ? (
            <PortalKanbanDeclinedIcon />
        ) : null
    const icons = [
        urgencyIcon,
        showAttachments ? <PortalKanbanPaperclipIcon key="attach" /> : null,
        showUnreadMessages ? <PortalKanbanMessageIcon key="msg" /> : null,
        statusIcon,
    ].filter(Boolean)
    if (icons.length === 0) return null
    return (
        <div style={{ display: "flex", alignItems: "center", flexWrap: "nowrap", gap: 4, flexShrink: 0, minHeight: 16, opacity: 0.75 }}>
            {icons}
        </div>
    )
}

