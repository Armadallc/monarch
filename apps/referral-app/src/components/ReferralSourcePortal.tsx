/** React onWheel is passive in browsers; use a non-passive capture listener to block page scroll. */
function useForwardWheelToScrollTarget(
    sourceRef: React.RefObject<HTMLDivElement | null>,
    targetRef: React.RefObject<HTMLDivElement | null>,
    enabled: boolean
) {
    useEffect(() => {
        const source = sourceRef.current
        if (!source || !enabled) return
        const onWheel = (e: WheelEvent) => {
            const target = targetRef.current
            if (!target) return
            target.scrollTop += e.deltaY
            if (e.deltaX) target.scrollLeft += e.deltaX
            e.preventDefault()
            e.stopPropagation()
        }
        source.addEventListener("wheel", onWheel, { passive: false, capture: true })
        return () => source.removeEventListener("wheel", onWheel, { capture: true })
    }, [sourceRef, targetRef, enabled])
}

