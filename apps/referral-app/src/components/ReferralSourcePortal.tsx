const MONARCH_DESKTOP_MIN_PX = 1200
const MONARCH_MOBILE_MAX_PX = 809
type MonarchViewport = {
    width: number
    isDesktop: boolean
    isTablet: boolean
    isMobile: boolean
    isNarrow: boolean
}
function useMonarchViewport(): MonarchViewport {
    const [width, setWidth] = useState(
        typeof window !== "undefined" ? window.innerWidth : MONARCH_DESKTOP_MIN_PX
    )
    useEffect(() => {
        if (typeof window === "undefined") return
        const update = () => setWidth(window.innerWidth)
        update()
        window.addEventListener("resize", update)
        return () => window.removeEventListener("resize", update)
    }, [])
    const isDesktop = width >= MONARCH_DESKTOP_MIN_PX
    const isMobile = width <= MONARCH_MOBILE_MAX_PX
    const isTablet = !isDesktop && !isMobile
    return { width, isDesktop, isTablet, isMobile, isNarrow: !isDesktop }
}
