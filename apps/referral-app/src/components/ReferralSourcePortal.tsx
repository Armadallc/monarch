function portalReferralHasAttachments(referral: PortalReferral): boolean {
    return (
        (Array.isArray(referral.uploaded_documents) && referral.uploaded_documents.length > 0) ||
        (Array.isArray(referral.documents_available) && referral.documents_available.length > 0)
    )
}

type ExpeditedPlacementDisplay = "none" | "lightning" | "lightning_circled"

function expeditedPlacementDisplay(
    urgentPlacement: boolean | undefined | null,
    urgencyLevel?: string | null
): ExpeditedPlacementDisplay {
    if (!urgentPlacement) return "none"
    if ((urgencyLevel || "").trim().toLowerCase() === "conditional_timeline") return "lightning_circled"
    return "lightning"
}

