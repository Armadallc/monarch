type DocumentInventoryStatus = "in_custody" | "can_obtain" | "unknown"

function parseDocumentsInventoryMap(raw: unknown): Record<string, DocumentInventoryStatus> {
    const map: Record<string, DocumentInventoryStatus> = {}
    if (!Array.isArray(raw)) return map
    if (raw.length > 0 && typeof raw[0] === "object" && raw[0] !== null && "type" in (raw[0] as object)) {
        for (const e of raw as { type: string; status: string }[]) {
            if (e.type && (e.status === "in_custody" || e.status === "can_obtain" || e.status === "unknown")) {
                map[e.type] = e.status
            }
        }
    }
    return map
}

function documentInventoryItemReceived(
    docType: string,
    uploaded: { document_type?: string | null }[],
    requestItems: { document_type: string; item_status: string }[]
): boolean {
    if (uploaded.some((d) => d.document_type === docType)) return true
    return requestItems.some(
        (i) => i.document_type === docType && (i.item_status === "uploaded" || i.item_status === "replaced")
    )
}

