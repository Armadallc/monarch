type PortalDocumentRequestSummary = {
    openCount: number
    batchCount: number
    roiRequired: boolean
    latestDueAt: string | null
}

function summarizePortalDocumentRequests(batches: PortalDocumentRequestBatchRow[]): PortalDocumentRequestSummary {
    let openCount = 0
    let roiRequired = false
    let latestDueAt: string | null = null
    for (const batch of batches) {
        if (batch.roi_required) roiRequired = true
        if (batch.due_at && (!latestDueAt || batch.due_at > latestDueAt)) latestDueAt = batch.due_at
        for (const item of batch.referral_document_request_items || []) {
            if (item.item_status === "requested" || item.item_status === "insufficient") openCount++
        }
    }
    return { openCount, batchCount: batches.length, roiRequired, latestDueAt }
}

const formatLabel = (value: string | null | undefined, labels?: Record<string, string>): string => {
    if (!value) return "\u2014"
    if (labels && labels[value]) return labels[value]
    return value.replace(/_/g, " ").replace(/\b\w/g, (c) => c.toUpperCase())
}
/** Postgres `date` / YYYY-MM-DD: local calendar day. Timestamps: local datetime. */
const formatDate = (date: string | null | undefined): string => {
    if (!date) return "\u2014"
    const s = String(date).trim()
    if (/^\d{4}-\d{2}-\d{2}$/.test(s)) {
        const [y, mo, d] = s.split("-").map((part) => parseInt(part, 10))
        return new Date(y, mo - 1, d).toLocaleDateString("en-US", {
            month: "short",
            day: "numeric",
            year: "numeric",
        })
    }
    return new Date(s).toLocaleDateString("en-US", {
        month: "short",
        day: "numeric",
        year: "numeric",
    })
}
const formatPhone = (phone: string | null | undefined): string => {
    if (!phone) return "\u2014"
    const digits = phone.replace(/\D/g, "")
    if (digits.length === 10) return `(${digits.slice(0, 3)}) ${digits.slice(3, 6)}-${digits.slice(6)}`
    return phone
}

